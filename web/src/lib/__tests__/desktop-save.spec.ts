import { afterEach, describe, expect, it, vi } from "vitest";

import { deleteGeneratedFile, generatedFileExtension, readGeneratedFileAsset, readGeneratedFileBlob, saveGeneratedFile } from "../desktop-save";

describe("desktop generated-file save", () => {
    afterEach(() => {
        delete (window as Window & { createDesktop?: unknown }).createDesktop;
    });

    it("sends the original bytes to the configured desktop save bridge", async () => {
        const saveBridge = vi.fn().mockResolvedValue({ savePath: "C:\\images\\image-1.png" });
        Object.assign(window, {
            createDesktop: {
                isDesktop: true,
                getSaveSettings: vi.fn(),
                saveSaveSettings: vi.fn(),
                chooseSaveDirectory: vi.fn(),
                openSaveFolder: vi.fn(),
                saveGeneratedFile: saveBridge,
            },
        });

        const blob = new Blob(["image-bytes"], { type: "image/png" });
        await expect(saveGeneratedFile(blob, "image", "image/png", "image-1.png")).resolves.toEqual({ savePath: "C:\\images\\image-1.png" });
        expect(saveBridge).toHaveBeenCalledTimes(1);
        const payload = saveBridge.mock.calls[0][0];
        expect(payload.kind).toBe("image");
        expect(payload.filename).toBe("image-1.png");
        expect(payload.data).toBeInstanceOf(ArrayBuffer);
    });

    it("deletes a generated file through the desktop bridge", async () => {
        const bridge = vi.fn().mockResolvedValue({ deleted: true, savePath: "C:\\images\\image-1.png" });
        Object.assign(window, {
            createDesktop: {
                isDesktop: true,
                getSaveSettings: vi.fn(),
                saveSaveSettings: vi.fn(),
                chooseSaveDirectory: vi.fn(),
                openSaveFolder: vi.fn(),
                deleteGeneratedFile: bridge,
            },
        });

        await expect(deleteGeneratedFile("image", "C:\\images\\image-1.png")).resolves.toEqual({ deleted: true, savePath: "C:\\images\\image-1.png" });
        expect(bridge).toHaveBeenCalledWith({ kind: "image", path: "C:\\images\\image-1.png" });
    });

    it("passes the canvas folder when saving a canvas asset", async () => {
        const saveBridge = vi.fn().mockResolvedValue({ savePath: "C:\\Pictures\\Create\\Canvas\\城市夜景-a1b2c3d4\\canvas.png" });
        Object.assign(window, {
            createDesktop: {
                isDesktop: true,
                getSaveSettings: vi.fn(),
                saveSaveSettings: vi.fn(),
                chooseSaveDirectory: vi.fn(),
                openSaveFolder: vi.fn(),
                saveGeneratedFile: saveBridge,
            },
        });

        const blob = new Blob(["canvas-image"], { type: "image/png" });
        await saveGeneratedFile(blob, "canvas", "image/png", "canvas.png", { canvasFolder: "城市夜景-a1b2c3d4" });

        expect(saveBridge).toHaveBeenCalledWith(expect.objectContaining({
            kind: "canvas",
            canvasFolder: "城市夜景-a1b2c3d4",
            filename: "canvas.png",
        }));
        expect(generatedFileExtension("canvas", "video/mp4")).toBe("mp4");
    });

    it("restores generated bytes from the desktop save bridge", async () => {
        const bridge = vi.fn().mockResolvedValue({
            data: new Uint8Array([1, 2, 3, 4]),
            savePath: "C:\\images\\image-1.png",
            mimeType: "image/png",
            size: 4,
        });
        Object.assign(window, {
            createDesktop: {
                isDesktop: true,
                getSaveSettings: vi.fn(),
                saveSaveSettings: vi.fn(),
                chooseSaveDirectory: vi.fn(),
                openSaveFolder: vi.fn(),
                readGeneratedFile: bridge,
            },
        });

        const asset = await readGeneratedFileAsset({ kind: "image", path: "C:\\images\\image-1.png", filename: "image-1.png", size: 4, mimeType: "image/png" });
        expect(asset?.savePath).toBe("C:\\images\\image-1.png");
        expect(bridge).toHaveBeenCalledWith(expect.objectContaining({ filename: "image-1.png" }));

        const blob = await readGeneratedFileBlob({ kind: "image", path: "C:\\images\\image-1.png", size: 4, mimeType: "image/png" });
        expect(blob?.type).toBe("image/png");
        expect(blob?.size).toBe(4);
    });
});
